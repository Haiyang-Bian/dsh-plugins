const test = require('node:test')
const assert = require('node:assert/strict')
const { environment, host, registerCustom } = require('./helpers.cjs')

const key = 'demo-sunset-theme:theme'
const log = { warn() {} }

test('restores a custom theme across activations and settings adoption', () => {
  const store = new Map()
  const env = environment({ store })
  const h = host()
  registerCustom(h)
  const { createThemePreference } = env.load('preferences.ts')
  const preference = createThemePreference(h.ctx, log)
  preference.select('sunset')
  assert.equal(store.get(key), 'sunset')
  assert.equal(h.writes.length, 0)
  h.adopt()
  assert.equal(h.state.preference, 'sunset')
  h.ctx.theme.setFontSize(22)
  h.adopt()
  assert.equal(h.state.preference, 'sunset')
  assert.equal(h.state.fontSize, 22)
  preference.dispose()
  preference.dispose()
  const fresh = host()
  registerCustom(fresh)
  const restored = createThemePreference(fresh.ctx, log)
  assert.equal(fresh.state.preference, 'sunset')
  restored.dispose()
  assert.equal(h.listeners.size, 0)
  assert.equal(fresh.listeners.size, 0)
})

for (const builtin of ['light', 'dark', 'system']) {
  test('selecting ' + builtin + ' hands preference ownership back to DSH', () => {
    const env = environment({ store: new Map([[key, 'sage']]) })
    const h = host()
    registerCustom(h)
    const preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
    preference.select(builtin)
    assert.equal(env.store.has(key), false)
    h.ctx.theme.setTheme(builtin === 'light' ? 'dark' : 'light')
    assert.equal(h.state.preference, builtin === 'light' ? 'dark' : 'light')
    preference.dispose()
  })
}

test('URL wins only during initialization; later user choices survive', () => {
  const env = environment({ search: '?theme=sunset', store: new Map([[key, 'sage']]) })
  const h = host()
  registerCustom(h)
  const preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
  assert.equal(h.state.preference, 'sunset')
  preference.select('aurora')
  env.runTimers()
  h.adopt()
  assert.equal(h.state.preference, 'aurora')
  assert.equal(env.timers.size, 0)
  preference.dispose()
})

test('built-in URL clears a saved custom theme', () => {
  const env = environment({ search: '?theme=system', store: new Map([[key, 'sage']]) })
  const h = host({ preference: 'dark' })
  registerCustom(h)
  const preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
  assert.equal(h.state.preference, 'system')
  assert.equal(env.store.has(key), false)
  preference.dispose()
})

test('invalid URL falls back to saved theme; invalid saved ids are removed', () => {
  const env = environment({ search: '?theme=missing', store: new Map([[key, 'sage']]) })
  const h = host()
  registerCustom(h)
  let preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
  assert.equal(h.state.preference, 'sage')
  preference.dispose()
  env.store.set(key, 'missing')
  h.ctx.theme.setTheme('dark')
  preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
  assert.equal(h.state.preference, 'dark')
  assert.equal(env.store.has(key), false)
  preference.dispose()
})

test('preference remains usable when browser storage is disabled', () => {
  const env = environment({ storageFaults: { read: true, write: true } })
  const h = host()
  registerCustom(h)
  const preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
  preference.select('sage')
  h.adopt()
  assert.equal(h.state.preference, 'sage')
  preference.dispose()
})

test('disposal stops reassertion before themes are removed', () => {
  const env = environment()
  const h = host()
  registerCustom(h)
  const preference = env.load('preferences.ts').createThemePreference(h.ctx, log)
  preference.select('sunset')
  preference.dispose()
  h.adopt()
  preference.select('sage')
  assert.equal(h.state.preference, 'system')
})
