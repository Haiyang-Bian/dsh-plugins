const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { environment, plugin, settingsHost } = require('./helpers.cjs')

test('renamed package, Node entry, loader and bundle agree on runtime identity', async () => {
  const env = environment()
  const entry = plugin(env)
  const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, '../package.json'), 'utf8'))
  const patch = fs.readFileSync(path.join(__dirname, '../cordis.patch.yml'), 'utf8')
  const node = await import('../index.js')
  assert.equal(manifest.name, 'dsh-appearance')
  assert.equal(manifest.version, '0.10.0')
  assert.equal(node.name, manifest.name)
  assert.equal(env.pluginId, manifest.name)
  assert.equal(entry.name, manifest.name)
  assert.match(patch, /id: dsh-appearance\s+name: dsh-appearance/)
})

test('new runtime restores and updates legacy preferences without new storage keys', async () => {
  const store = new Map([
    ['demo-sunset-theme:font', 'custom'], ['demo-sunset-theme:custom-font', 'Georgia'],
    ['demo-sunset-theme:theme', 'sage'],
  ])
  const env = environment({ store })
  const h = await settingsHost()
  plugin(env).apply(h.ctx)
  assert.equal(h.state.preference, 'sage')
  assert.equal(h.ctx.theme.getTheme().active.tokens['--dsw-font-family'], 'Georgia')
  h.face('appearance').selectTheme('aurora')
  h.face('dsh-appearance-font').selectFont('mono')
  assert.equal(store.get('demo-sunset-theme:theme'), 'aurora')
  assert.equal(store.get('demo-sunset-theme:font'), 'mono')
  assert.equal([...store.keys()].some(key => key.startsWith('dsh-appearance:')), false)
  await h.dispose()
  assert.equal(h.listeners.size, 0)
  assert.equal(h.overrides.size, 0)
})

test('new export name keeps legacy OPFS history and Web Locks identity', async () => {
  const env = environment({ opfs: true, opfsContent: 'history from original plugin\n' })
  const { Log } = env.load('log.ts')
  const log = new Log()
  await log.init()
  log.log('renamed activation')
  await log.exportAsFile()
  assert.match(await env.downloads[0].text(), /history from original plugin/)
  assert.match(await env.downloads[0].text(), /renamed activation/)
  assert.deepEqual(env.opfs.filenames, ['demo-sunset-theme.log'])
  assert.ok(env.lockNames.every(name => name === 'demo-sunset-theme:log'))
  assert.match(env.document.downloadNames[0], /^dsh-appearance-\d{4}-\d{2}-\d{2}\.log$/)
  await log.dispose()
  assert.equal(env.opfs.active, 0)
  assert.equal(env.blobs.size, 0)
})

test('legacy localStorage log remains the fallback after rename', async () => {
  const store = new Map([['demo-sunset-theme:log', 'saved local history\n']])
  const env = environment({ store })
  const { Log } = env.load('log.ts')
  const log = new Log()
  await log.init()
  log.log('new local entry')
  const text = await log.readPersisted()
  assert.match(text, /saved local history/)
  assert.match(text, /new local entry/)
  assert.equal(store.has('dsh-appearance:log'), false)
  await log.dispose()
})
